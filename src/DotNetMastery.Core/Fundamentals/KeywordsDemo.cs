namespace DotNetMastery.Core.Fundamentals;

/// <summary>
/// Demonstrates key C# keywords covered in the guide:
/// - ref vs out
/// - const vs readonly
/// - var vs dynamic
/// - yield return (lazy evaluation)
/// - Equals() vs ==
/// - enum and nameof vs ToString()
/// </summary>
public static class KeywordsDemo
{
    // ==========================================
    // 1. ref vs out
    // ==========================================

    /// <summary>
    /// ref requires the variable to be initialized BEFORE calling the method.
    /// The method can inspect and mutate the original variable.
    /// </summary>
    public static void Increment(ref int value)
    {
        value++;
    }

    /// <summary>
    /// out does NOT require pre-initialization by caller.
    /// The method MUST assign a value before returning.
    /// </summary>
    public static bool TryParseInteger(string input, out int result)
    {
        if (int.TryParse(input, out result))
        {
            return true;
        }

        result = 0; // Mandatory assignment
        return false;
    }

    /// <summary>
    /// Returning multiple values using out parameters.
    /// </summary>
    public static void GetUserInfo(int id, out string name, out int age)
    {
        name = $"User_{id}";
        age = 25 + (id % 10);
    }

    // ==========================================
    // 2. const vs readonly
    // ==========================================

    public class ConfigurationHolder
    {
        // const: compile-time constant, inlined at call sites, cannot be changed
        public const string ApiVersion = "v1.0";
        public const int MaxRetryAttempts = 3;

        // readonly: runtime constant, initialized at declaration or inside the constructor
        public readonly string EnvironmentName;
        public readonly DateTime CreatedAtUtc;

        public ConfigurationHolder(string environmentName)
        {
            EnvironmentName = environmentName;
            CreatedAtUtc = DateTime.UtcNow;
        }
    }

    // ==========================================
    // 3. var vs dynamic
    // ==========================================

    /// <summary>
    /// var: statically typed at compile time (type inference). Full IntelliSense and safety.
    /// </summary>
    public static string DemonstrateVarInference()
    {
        var message = "Hello, World!"; // Inferred as string at compile-time
        return message.ToUpperInvariant();
    }

    /// <summary>
    /// dynamic: late-bound at runtime. Bypasses compile-time checking.
    /// Useful for COM interop, reflection, or dynamic JSON parsing, but carries runtime overhead.
    /// </summary>
    public static object EvaluateDynamicOperation(dynamic operandA, dynamic operandB)
    {
        // Runtime method dispatch / operator resolution
        return operandA + operandB;
    }

    // ==========================================
    // 4. yield (Lazy Evaluation)
    // ==========================================

    /// <summary>
    /// Eager generation: allocates the entire list of numbers in memory up front.
    /// </summary>
    public static List<int> GenerateNumbersEager(int count)
    {
        var list = new List<int>(count);
        for (int i = 1; i <= count; i++)
        {
            list.Add(i);
        }
        return list;
    }

    /// <summary>
    /// Lazy generation with yield return: generates items on demand without allocating the whole collection.
    /// State machine generated by the compiler.
    /// </summary>
    public static IEnumerable<int> GenerateNumbersLazy(int count)
    {
        for (int i = 1; i <= count; i++)
        {
            yield return i;
        }
    }

    // ==========================================
    // 5. Equals() vs ==
    // ==========================================

    public class PersonClass
    {
        public string Name { get; set; } = string.Empty;

        public override bool Equals(object? obj) =>
            obj is PersonClass other && Name == other.Name;

        public override int GetHashCode() => Name.GetHashCode();
    }

    public record PersonRecord(string Name);

    /// <summary>
    /// Demonstrates the difference between reference equality (== by default for classes)
    /// and value equality (.Equals() or records).
    /// </summary>
    public static (bool operatorEquality, bool equalsMethod, bool recordEquality) CompareEqualities()
    {
        var class1 = new PersonClass { Name = "Alice" };
        var class2 = new PersonClass { Name = "Alice" };

        // For classes without overloaded ==, == checks reference equality
        bool operatorEq = (class1 == class2); // false (different references on heap)
        bool equalsEq = class1.Equals(class2); // true (custom Equals() checks Name)

        var rec1 = new PersonRecord("Alice");
        var rec2 = new PersonRecord("Alice");
        bool recordEq = (rec1 == rec2); // true (records synthesize value-based equality)

        return (operatorEq, equalsEq, recordEq);
    }

    // ==========================================
    // 6. enum and nameof vs ToString()
    // ==========================================

    public enum UserStatus
    {
        Pending = 0,
        Active = 1,
        Suspended = 2,
        Deleted = 3
    }

    /// <summary>
    /// status.ToString() uses reflection and allocates a new string object on the heap.
    /// nameof(UserStatus.Active) is a compile-time string literal with zero allocations.
    /// For runtime enum values, switch expressions provide zero-allocation formatting.
    /// </summary>
    public static string GetStatusNameFast(UserStatus status) => status switch
    {
        UserStatus.Pending => nameof(UserStatus.Pending),
        UserStatus.Active => nameof(UserStatus.Active),
        UserStatus.Suspended => nameof(UserStatus.Suspended),
        UserStatus.Deleted => nameof(UserStatus.Deleted),
        _ => "Unknown"
    };
}
